class Portfolio extends Component {

  constructor(props) {
    super(props);
    this.state = { selected: 'All' };
  }
  handleSelectFilter = (filter) => this.setState({ selected: filter });

  render() {
    const { selected } = this.state;
    const filters = ['All', 'Websites', 'Flayers', 'Business Cards'];
    const filteredProjects = selected === 'All' ? projects : projects.filter(p => p.category === selected);

    return (
      <div className="portfolio-container">
        <Toolbar filters={filters} selected={selected} onSelectFilter={this.handleSelectFilter} />
        <ProjectList projects={filteredProjects} />
      </div>
    );
  }
}

export default Portfolio;